"""Step 5 - write docs/findings.md. Every number is read from the pipeline outputs, so the write-up cannot drift from the analysis."""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "processed"


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---:" if pd.api.types.is_numeric_dtype(df[c]) else "---" for c in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def main() -> None:
    m = json.loads((DATA / "model_metrics.json").read_text())
    log = json.loads((DATA / "cleaning_log.json").read_text())
    l = pd.read_csv(DATA / "listings_clean.csv")
    shap = pd.read_csv(DATA / "shap_importance.csv")
    ols = pd.read_csv(DATA / "ols_coefficients.csv")
    nb = pd.read_csv(DATA / "neighbourhood_effects.csv")
    rv = pd.read_csv(DATA / "seasonality_reviews_by_month.csv")
    cal = pd.read_csv(DATA / "seasonality_calendar_by_month.csv")
    wd = pd.read_csv(DATA / "seasonality_calendar_by_weekday.csv")
    pred = pd.read_csv(DATA / "listing_predictions.csv")

    rt = l.groupby("room_type").price_gbp.agg(["size", "median"]).round(0).astype(int).reset_index()
    rt.columns = ["Room type", "Listings", "Median £/night"]
    rel = nb[nb.reliable].sort_values("premium_pct_vs_city", ascending=False)
    top_nb = rel.head(8)[["neighbourhood", "listings", "median_price", "premium_pct_vs_city"]].copy()
    top_nb.columns = ["Neighbourhood", "Listings", "Median £/night", "Premium vs city (%)"]
    low_nb = rel.tail(8).iloc[::-1][["neighbourhood", "listings", "median_price", "premium_pct_vs_city"]].copy()
    low_nb.columns = top_nb.columns
    top_nb["Median £/night"] = top_nb["Median £/night"].round(0).astype(int); low_nb["Median £/night"] = low_nb["Median £/night"].round(0).astype(int)

    imp = shap.head(10)[["label", "approx_pct_swing"]].copy()
    imp.columns = ["Driver", "Typical swing in price (± %)"]

    cc = ols[(ols.p_value < 0.05) & ~ols.term.str.startswith("np.log")].copy()
    cc = cc.reindex(cc.pct_effect.abs().sort_values(ascending=False).index).head(10)
    cc["term"] = cc["term"].str.replace(r"C\((\w+)\)\[T\.(.*)\]", r"\1: \2", regex=True)
    cc = cc[["term", "pct_effect", "ci_low_pct", "ci_high_pct"]].round(1)
    cc.columns = ["Term", "% effect", "CI low", "CI high"]

    peak, trough = rv.loc[rv.seasonal_index.idxmax()], rv.loc[rv.seasonal_index.idxmin()]
    full = cal[~cal.partial_month]
    wk = wd.set_index("weekday").unavailable_share
    over = pred[pred.gap_pct >= 40]
    under = pred[pred.gap_pct <= -40]

    met = pd.DataFrame([
        ["Global median", m["baseline_global_median"]],
        ["Neighbourhood x room-type median", m["baseline_neighbourhood_roomtype_median"]],
        ["Linear model (fixed effects)", m["ols_fixed_effects_only"]],
        ["Mixed model (+ neighbourhood effects)", m["mixed_model_with_neighbourhood_effects"]],
        ["LightGBM, listing attributes only (no reviews/availability)", m["gbm_listing_attributes_only_test"]],
        ["LightGBM, all features", m["gbm_test"]],
        ["LightGBM, unseen neighbourhoods (5-fold group CV, no neighbourhood feature)", m["gbm_unseen_neighbourhoods_groupcv"]],
    ], columns=["Model", "d"])
    for k, name in [("r2_log_price", "R² (log price)"), ("median_abs_error_gbp", "Median abs. error (£)"), ("mae_gbp", "MAE (£)"), ("median_abs_pct_error", "Median abs. % error")]:
        met[name] = met["d"].map(lambda d: d[k])
    met = met.drop(columns="d")

    text = f"""# Findings (auto-generated by `src/report.py`)

Edinburgh Airbnb listings, Inside Airbnb scrape of 2026-09-19 (CC BY 4.0). Prices are nightly list prices as published (treated as GBP).

## Data
* {log['rows_raw']:,} listings published; **{log['rows_model_ready']:,}** used after cleaning ({log['dropped_missing_price']:,} had no price, {log['dropped_price_outside_20_1500']} priced outside £20-£1,500, {log['dropped_long_stay_over_28_nights']} long-stay lets, hotel/shared rooms excluded).
* Median nightly price **£{l.price_gbp.median():.0f}**; middle 50% of listings £{l.price_gbp.quantile(.25):.0f}-£{l.price_gbp.quantile(.75):.0f}.

{md(rt)}

## 1. How well can price be predicted?
Test set = {m['n_test']:,} listings never used for fitting or tuning.

{md(met)}

* The simple neighbourhood x room-type median misses by a median of **£{m['baseline_neighbourhood_roomtype_median']['median_abs_error_gbp']:.0f}** a night; gradient boosting brings that to **£{m['gbm_test']['median_abs_error_gbp']:.0f}** (R² {m['gbm_test']['r2_log_price']:.2f} on log price).
* Predicting neighbourhoods the model has never seen costs little accuracy (R² {m['gbm_unseen_neighbourhoods_groupcv']['r2_log_price']:.2f}), so the model is learning transferable drivers rather than memorising areas.
* Dropping reviews/availability (which partly *react* to price) leaves R² {m['gbm_listing_attributes_only_test']['r2_log_price']:.2f}: most of the signal is in the listing itself.

![Model comparison](../outputs/fig_model_comparison.png)

## 2. Price drivers
Gradient boosting + SHAP (average swing in price caused by each driver):

{md(imp)}

![SHAP summary](../outputs/fig_shap_summary.png)

Linear model, largest significant effects holding other factors fixed:

{md(cc)}

![Linear effects](../outputs/fig_ols_effects.png)

**Caution:** reviews per month, availability and ratings are partly *consequences* of price (cheap places book up and collect reviews). They help prediction but should not be read as levers a host could pull.

## 3. Neighbourhood effects
After controlling for size, quality and distance, neighbourhood explains **{m['share_of_unexplained_variance_between_neighbourhoods']*100:.0f}%** of the remaining variation in price; the rest is listing-level. Premiums below come from a mixed model with a random intercept per neighbourhood, which shrinks small areas towards the city average. Only neighbourhoods with at least 10 listings are shown ({int(nb.reliable.sum())} of {len(nb)}).

Highest premium:

{md(top_nb)}

Lowest:

{md(low_nb)}

![Median price map](../outputs/fig_map_median_price.png)
![Premium map](../outputs/fig_map_premium.png)

Interactive version with a third layer showing every listing against the model's fair price: `outputs/edinburgh_price_map.html`. **{len(over):,}** listings are priced at least 40% above the model's fair price and **{len(under):,}** at least 40% below.

## 4. Seasonality
The current calendar file has no nightly prices, so seasonality is measured by guest demand (review volume, which follows stays) and forward availability.
* Demand peaks in **{peak.month_name}** (index {peak.seasonal_index:.2f}; the Festival month) and is lowest in **{trough.month_name}** ({trough.seasonal_index:.2f}), a {peak.seasonal_index/trough.seasonal_index:.1f}x swing. May-Sep all run above average.
* Over the next 12 months the share of unavailable listing-nights runs from {100*full.unavailable_share.min():.0f}% ({full.loc[full.unavailable_share.idxmin(),'year_month']}) to {100*full.unavailable_share.max():.0f}% ({full.loc[full.unavailable_share.idxmax(),'year_month']}). Unavailable includes host-blocked nights, so this is an upper bound on bookings.
* By weekday, unavailability is highest on {wk.idxmax()} ({100*wk.max():.0f}%) and lowest on {wk.idxmin()} ({100*wk.min():.0f}%).

![Seasonality](../outputs/fig_seasonality.png)

## Limitations
* One snapshot: prices are asking prices at scrape time, not what guests paid.
* Seasonality is demand-based, not price-based, because the calendar file carries no prices.
* Reviews are a lagged and imperfect proxy for stays; early-year review volumes are also affected by the pandemic recovery (each year is normalised by its own average).
* Associations, not causal effects. Amenities are text-matched from the host's list.
"""
    (ROOT / "docs" / "findings.md").write_text(text, encoding="utf-8")
    print("wrote docs/findings.md")


if __name__ == "__main__":
    main()
